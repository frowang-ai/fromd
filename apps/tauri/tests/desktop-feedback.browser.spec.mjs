import {test,expect} from '@playwright/test'
import {installMockHost} from './mock-host.mjs'

async function boot(page,options={}){
 await page.addInitScript(installMockHost,options)
 await page.goto('/?testHost=1')
 await expect(page.locator('.loading-state')).toHaveCount(0)
 await expect(page.locator('.ProseMirror:visible')).toBeVisible()
}
const source=page=>page.getByRole('textbox',{name:'Markdown 源码',exact:true})

test('tab context menu follows pointer, clamps edges and keeps clicked document ownership',async({page})=>{
 await boot(page)
 const tab=page.locator('[data-tab-id="b"]')
 const box=await tab.boundingBox(),x=box.x+20,y=box.y+10
 await page.mouse.click(x,y,{button:'right'})
 const menu=page.getByRole('menu')
 await expect(menu).toBeVisible()
 const rect=await menu.boundingBox()
 expect(Math.abs(rect.x-x)).toBeLessThan(3);expect(Math.abs(rect.y-y)).toBeLessThan(3)
 await expect(page.locator('.tab.selected')).toHaveAttribute('data-tab-id','a')
 await menu.getByRole('menuitem',{name:'收起',exact:true}).click()
 await expect(page.locator('[data-tab-id="b"]')).toHaveCount(0)
 await expect(page.locator('.tab.selected')).toHaveAttribute('data-tab-id','a')
 await page.locator('[data-tab-id="a"]').dispatchEvent('contextmenu',{clientX:1278,clientY:858})
 const edge=await menu.boundingBox()
 expect(edge.x+edge.width).toBeLessThanOrEqual(1280);expect(edge.y+edge.height).toBeLessThanOrEqual(860)
 await page.keyboard.press('Escape');await expect(menu).toHaveCount(0)
 await page.getByRole('button',{name:'页面菜单 方案讨论',exact:true}).click()
 const anchor=await page.getByRole('button',{name:'页面菜单 方案讨论',exact:true}).boundingBox()
 expect((await menu.boundingBox()).y).toBeCloseTo(anchor.y+anchor.height,0)
 await page.locator('.brand').click();await expect(menu).toHaveCount(0)
})

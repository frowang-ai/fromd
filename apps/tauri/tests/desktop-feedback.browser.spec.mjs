test('sidebar close keeps the draft on save cancel/failure, then reuses save-before-remove',async({page})=>{
 await boot(page)
 for(const choice of ['cancel','fail']){
  await page.evaluate(choice=>window.__FROWD_TEST_HOST__.saveChoice=choice,choice)
  await page.getByRole('button',{name:'关闭页面 方案讨论',exact:true}).click()
  await page.getByRole('button',{name:'保存为 Markdown',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('[data-tab-id="a"]')).toBeVisible()
  expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.rows.get('a').markdown)).toContain('合成文稿')
 }
 await expect(page.getByRole('alert')).toContainText('合成文件保存失败')
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.saveChoice='save')
 await page.getByRole('button',{name:'关闭页面 方案讨论',exact:true}).click()
 await page.getByRole('button',{name:'保存为 Markdown',exact:true}).click()
 await expect(page.locator('[data-page-id="a"]')).toHaveCount(0)
 await page.getByRole('button',{name:'撤销',exact:true}).click()
 await expect(page.locator('.name-dock .file-name')).toHaveText('方案讨论')
 expect(await page.evaluate(()=>[...window.__FROWD_TEST_HOST__.rows.values()].find(d=>d.title==='方案讨论').path)).toBe('/synthetic/方案讨论.md')
})
test('Ctrl slash switches body/source and consumes embedded editor shortcuts with IME guard',async({page})=>{
 await boot(page,{markdown:'```js\nconst answer=42;\n```'})
 await page.locator('.cm-content').click()
 await page.keyboard.press('Control+/');await expect(source(page)).toBeVisible()
 await source(page).dispatchEvent('keydown',{key:'Process',code:'Slash',ctrlKey:true,isComposing:true,keyCode:229})
 await expect(source(page)).toBeVisible()
 await source(page).dispatchEvent('keydown',{key:'、',code:'Slash',ctrlKey:true,bubbles:true,cancelable:true})
 await expect(page.locator('.ProseMirror:visible')).toBeVisible()
 await page.getByText('视图',{exact:true}).click()
 await expect(page.getByRole('button',{name:/源码/})).toContainText('Ctrl+/')
})
test('zoom shortcuts, wheel and menu share bounded page zoom without changing Markdown or reading font',async({page})=>{
 await boot(page)
 const shell=page.locator('.app-shell'),body=page.locator('.ProseMirror:visible')
 const markdown=await page.evaluate(()=>window.__FROWD_TEST_HOST__.rows.get('a').markdown)
 const font=await body.evaluate(el=>getComputedStyle(el).fontSize)
 await body.click();await page.keyboard.press('Control+=')
 await expect(shell).toHaveAttribute('data-zoom','110')
 await body.dispatchEvent('wheel',{ctrlKey:true,deltaY:-100,bubbles:true,cancelable:true})
 await expect(shell).toHaveAttribute('data-zoom','120')
 await page.keyboard.press('Control+-');await expect(shell).toHaveAttribute('data-zoom','110')
 await page.getByText('视图',{exact:true}).click();await page.getByRole('button',{name:/实际大小/}).click()
 await expect(shell).toHaveAttribute('data-zoom','100')
 for(let i=0;i<20;i++)await page.keyboard.press('Control+-')
 await expect(shell).toHaveAttribute('data-zoom','50')
 await page.keyboard.press('Control+0');await expect(shell).toHaveAttribute('data-zoom','100')
 expect(await body.evaluate(el=>getComputedStyle(el).fontSize)).toBe(font)
 expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.rows.get('a').markdown)).toBe(markdown)
})

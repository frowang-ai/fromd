import {test,expect} from '@playwright/test'
import {installMockHost} from './mock-host.mjs'
async function boot(page,options={},query=''){
 await page.addInitScript(installMockHost,options)
 await page.goto('/?testHost=1'+query)
 await expect(page.locator('.ProseMirror')).toBeVisible()
 await expect(page.locator('.loading-state')).toHaveCount(0)
}
async function check(page){await page.locator('.app-menu summary').filter({hasText:'文件'}).click();await page.getByRole('button',{name:'检查更新…',exact:true}).click()}
const notice=page=>page.getByRole('status',{name:'应用更新',exact:true})
for(const theme of ['light','dark'])test(`manual check latest status and close (${theme})`,async({page})=>{
 await boot(page,{holds:['check_updates'],updateResult:{currentVersion:'0.5.2',version:null,platform:'windows'}})
 expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.entered.check_updates||0)).toBe(0)
 await expect(notice(page)).toHaveCount(0)
 if(theme==='dark'){
  await page.getByRole('button',{name:'阅读设置',exact:true}).click()
  await page.getByLabel('主题').selectOption('dark')
  await page.getByRole('button',{name:'关闭阅读设置'}).click()
 }
 await check(page);await expect(notice(page)).toContainText('正在检查更新')
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.release('check_updates'))
 await expect(notice(page)).toContainText('当前已是最新版本（v0.5.2）')
 const box=await notice(page).boundingBox();expect(box.x).toBe(12);expect(Math.round(860-box.y-box.height)).toBe(12)
 const colors=await notice(page).evaluate(el=>({bg:getComputedStyle(el).backgroundColor,fg:getComputedStyle(el).color}))
 expect(colors.bg).not.toBe(colors.fg)
 await notice(page).getByRole('button',{name:'关闭更新提示'}).click();await expect(notice(page)).toHaveCount(0)
})
test('download progress preserves editor availability, final body/title/view and shelved page before frozen handoff',async({page})=>{
 await boot(page,{holds:['download_update']})
 await check(page);await expect(notice(page)).toContainText('发现新版本 v0.6.0')
 await notice(page).getByRole('button',{name:'立即更新'}).click()
 await expect.poll(()=>page.evaluate(()=>window.__FROWD_TEST_HOST__.entered.download_update||0)).toBe(1)
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.updateProgress(45,100))
 await expect(notice(page)).toContainText('45%')
 await expect(page.locator('.ProseMirror')).toHaveAttribute('contenteditable','true')
 // Native close during a download is cancelled; it must not race the installer handoff.
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.requestClose())
 expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.closed)).toBe(false)
 const name=page.getByRole('textbox',{name:'当前页面名称'})
 await name.evaluate(el=>{el.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true}));el.value='最后组合标题';el.dispatchEvent(new InputEvent('input',{bubbles:true,isComposing:true}))})
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.release('download_update'))
 await expect(notice(page)).toContainText('正在保存文稿并启动安装程序')
 expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.entered.install_update||0)).toBe(0)
 await name.evaluate(el=>el.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true,data:'最后组合标题'})))
 await expect.poll(()=>page.evaluate(()=>window.__FROWD_TEST_HOST__.closed)).toBe(true)
 const result=await page.evaluate(()=>{const h=window.__FROWD_TEST_HOST__;return{calls:h.calls.map(c=>c.command),snapshot:h.installedSnapshot,frozen:h.frozenAtUpdate}})
 expect(result.frozen).toBe(true)
 expect(result.snapshot.rows.find(d=>d.id==='a').title).toBe('最后组合标题')
 expect(result.snapshot.rows.find(d=>d.id==='c').shelved).toBe(true)
 expect(result.snapshot.rows.find(d=>d.id==='a').viewState).not.toBeNull()
 expect(result.calls.lastIndexOf('install_update')).toBeGreaterThan(result.calls.lastIndexOf('checkpoint'))
 await expect(page.locator('.ProseMirror')).toHaveAttribute('contenteditable','false')
})
test('body IME final input is captured before update spawn',async({page})=>{
 await boot(page,{holds:['download_update']});await check(page);await notice(page).getByRole('button',{name:'立即更新'}).click()
 await page.locator('.app-menu summary').filter({hasText:'视图'}).click();await page.getByRole('button',{name:/^源码/}).click()
 const source=page.locator('.markdown-source')
 await expect(source).toBeVisible()
 await source.evaluate(el=>{el.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true}));el.value+='\n最后组合正文';el.dispatchEvent(new InputEvent('input',{bubbles:true,isComposing:true,inputType:'insertCompositionText',data:'最后组合正文'}))})
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.release('download_update'))
 await expect(notice(page)).toContainText('正在保存文稿')
 expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.entered.install_update||0)).toBe(0)
 await source.evaluate(el=>el.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true,data:'最后组合正文'})))
 await expect.poll(()=>page.evaluate(()=>window.__FROWD_TEST_HOST__.closed)).toBe(true)
 expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.installedSnapshot.rows.find(d=>d.id==='a').markdown)).toContain('最后组合正文')
})
for(const command of ['check_updates','download_update','checkpoint','install_update'])test(`${command} error keeps window/editing and retry succeeds`,async({page})=>{
 await boot(page)
 await page.evaluate(command=>window.__FROWD_TEST_HOST__.fail=command,command)
 await check(page)
 if(command!=='check_updates')await notice(page).getByRole('button',{name:'立即更新'}).click()
 await expect(notice(page)).toContainText('合成写入失败')
 expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.closed)).toBe(false)
 await expect(page.locator('.ProseMirror')).toHaveAttribute('contenteditable','true')
 await page.locator('.ProseMirror').click();await page.keyboard.press('Control+End');await page.keyboard.type(' retry text')
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.fail=null)
 await notice(page).getByRole('button',{name:'重试',exact:true}).click()
 if(command==='check_updates')await expect(notice(page)).toContainText('发现新版本')
 else {
  await expect.poll(()=>page.evaluate(()=>window.__FROWD_TEST_HOST__.closed)).toBe(true)
  expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.installedSnapshot.rows.find(d=>d.id==='a').markdown)).toContain('retry text')
 }
})

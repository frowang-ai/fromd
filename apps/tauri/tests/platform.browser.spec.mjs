test('macOS leaves Cmd+W to AppKit and closes through the handshake on an empty desktop',async({page})=>{
 await boot(page,'macos',{native:true})
 const collapse=()=>page.evaluate(()=>window.__FROWD_TEST_HOST__.menuCommand('collapse'))
 await expect(page.locator('[data-tab-id="a"] .tab-minus')).toHaveAttribute('title','收起（⌘W）')
 const intercepted=await page.evaluate(()=>{
  const event=new KeyboardEvent('keydown',{key:'w',metaKey:true,bubbles:true,cancelable:true})
  window.dispatchEvent(event)
  return event.defaultPrevented
 })
 expect(intercepted).toBe(false)
 await expect(page.locator('.tab.selected')).toHaveAttribute('data-tab-id','a')
 await collapse()
 await expect(page.locator('.tab.selected')).toHaveAttribute('data-tab-id','b')
 await expect(page.locator('.tab.selected .tab-minus')).toBeEnabled()
 await collapse()
 await expect(page.locator('.empty-desktop')).toBeVisible()
 await expect(page.locator('.new-tab')).toBeEnabled()
 expect(await page.evaluate(()=>window.__FROWD_TEST_HOST__.closed)).toBe(false)
 await collapse()
 await expect.poll(()=>page.evaluate(()=>window.__FROWD_TEST_HOST__.closed)).toBe(true)
 const calls=await page.evaluate(()=>window.__FROWD_TEST_HOST__.calls.map(c=>c.command))
 expect(calls.filter(command=>command==='shelve_document')).toHaveLength(2)
 expect(calls.indexOf('checkpoint')).toBeLessThan(calls.indexOf('close_ready'))
})

test('collapse skips composition and the removal dialog and consumes a busy key without queueing it',async({page})=>{
 await boot(page,'windows')
 const body=page.locator('.ProseMirror:visible')
 const count=()=>page.evaluate(()=>window.__FROWD_TEST_HOST__.entered.shelve_document||0)
 await body.focus()
 await body.dispatchEvent('compositionstart',{data:''})
 await page.keyboard.press('Control+w')
 expect(await count()).toBe(0)
 await body.dispatchEvent('compositionend',{data:''})
 await page.getByRole('button',{name:'关闭页面 方案讨论',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'保留这篇笔记？'})
 await expect(dialog).toBeVisible()
 await page.keyboard.press('Control+w')
 expect(await count()).toBe(0)
 await dialog.getByRole('button',{name:'取消'}).click()
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.holds.add('shelve_document'))
 await page.keyboard.press('Control+w')
 await expect.poll(count).toBe(1)
 const consumed=await page.evaluate(()=>{
  const event=new KeyboardEvent('keydown',{key:'w',ctrlKey:true,bubbles:true,cancelable:true})
  window.dispatchEvent(event)
  return event.defaultPrevented
 })
 expect(consumed).toBe(true)
 await page.evaluate(()=>window.__FROWD_TEST_HOST__.release('shelve_document'))
 await expect(page.locator('.tab.selected')).toHaveAttribute('data-tab-id','b')
 expect(await count()).toBe(1)
})
